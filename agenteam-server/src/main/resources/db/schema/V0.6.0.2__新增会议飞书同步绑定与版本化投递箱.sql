-- 会议飞书同步：字段绑定与版本化投递箱。
-- 统一企业飞书 Base，会议主表与会议督办宽表各一条 Binding；系统到飞书方向，
-- Outbox 只存待投递的受控字段快照，飞书是业务状态唯一事实来源。

CREATE TABLE meeting_binding (
  `id` varchar(100) NOT NULL,
  `enterprise_id` varchar(100) NOT NULL,
  `revision` bigint NOT NULL DEFAULT 1,
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `integration_id` varchar(100) NOT NULL COMMENT '飞书应用接入，凭据与数据隔离',
  `name` varchar(160) NOT NULL COMMENT '绑定名称',
  `app_token` varchar(191) NOT NULL COMMENT '统一 Base app token',
  `table_id` varchar(191) NOT NULL COMMENT '目标表 id',
  `business_type` varchar(32) NOT NULL COMMENT 'meeting 会议主表 / task 会议督办宽表',
  `key_field` varchar(191) NOT NULL COMMENT '业务唯一键对应的飞书字段名',
  `field_mapping_json` json NOT NULL COMMENT '业务字段编码 -> 飞书字段名，仅系统可写字段',
  `writeback_json` json DEFAULT NULL COMMENT '结果键 -> 飞书字段名，回写同步状态/时间/记录',
  `status` varchar(32) NOT NULL DEFAULT 'disabled' COMMENT '启用、停用或删除',
  `schema_revision` varchar(64) DEFAULT NULL COMMENT '绑定校验时的飞书 schema 快照',
  `owner_user_id` varchar(100) NOT NULL COMMENT '配置者，作为受控服务身份',
  `config_json` json NOT NULL DEFAULT (JSON_OBJECT()) COMMENT '预留扩展配置',
  PRIMARY KEY (`id`),
  UNIQUE KEY uk_meeting_binding_scope (enterprise_id, id),
  UNIQUE KEY uk_meeting_binding_0 (enterprise_id, business_type),
  KEY idx_meeting_binding_0 (enterprise_id, status),
  CONSTRAINT fk_meeting_binding_enterprise FOREIGN KEY (enterprise_id) REFERENCES enterprise(id),
  CONSTRAINT fk_meeting_binding_1 FOREIGN KEY (enterprise_id, integration_id) REFERENCES enterprise_integration(enterprise_id, id),
  CONSTRAINT fk_meeting_binding_member FOREIGN KEY (enterprise_id, owner_user_id) REFERENCES enterprise_member(enterprise_id, user_id),
  CONSTRAINT ck_meeting_binding_revision CHECK (revision > 0),
  CONSTRAINT ck_meeting_binding_status CHECK (status IN ('enabled','disabled','deleted')),
  CONSTRAINT ck_meeting_binding_business_type CHECK (business_type IN ('meeting','task'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='企业统一飞书 Base 的字段绑定，schema 校验后启用';

CREATE TABLE meeting_sync_outbox (
  `id` varchar(100) NOT NULL,
  `enterprise_id` varchar(100) NOT NULL,
  `revision` bigint NOT NULL DEFAULT 1,
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `binding_id` varchar(100) NOT NULL COMMENT '所属绑定',
  `business_key` varchar(191) NOT NULL COMMENT '稳定业务唯一键值，等于 key_field 对应字段值',
  `command_id` varchar(100) NOT NULL COMMENT '最近一次入队命令 id，用于对账',
  `desired_version` bigint NOT NULL DEFAULT 1 COMMENT '期望投递版本，入队递增',
  `delivered_version` bigint NOT NULL DEFAULT 0 COMMENT '已确认投递版本，仅在明确成功后推进',
  `record_id` varchar(191) DEFAULT NULL COMMENT '飞书记录 id，创建或对账后回填',
  `create_token` varchar(100) NOT NULL COMMENT '幂等创建 client_token，记录生命周期内稳定',
  `claim_token` varchar(100) DEFAULT NULL COMMENT '领取栅栏 token',
  `lease_until` datetime(3) DEFAULT NULL COMMENT '领取租约到期时间',
  `attempt_count` int NOT NULL DEFAULT 0 COMMENT '累计尝试次数',
  `max_attempts` int NOT NULL DEFAULT 8 COMMENT '自动重试上限',
  `next_attempt_at` datetime(3) NOT NULL COMMENT '下次可投递时间，失败退避后延',
  `payload_json` json NOT NULL DEFAULT (JSON_OBJECT()) COMMENT '待投递字段级 patch，仅系统可写字段',
  `last_error_code` varchar(64) DEFAULT NULL,
  `last_request_id` varchar(191) DEFAULT NULL,
  `run_id` varchar(100) DEFAULT NULL COMMENT '关联分析 Run，用于审计与找回',
  `status` varchar(32) NOT NULL DEFAULT 'pending' COMMENT 'pending/delivered/failed/blocked，领取由 claim_token 栅栏表达',
  PRIMARY KEY (`id`),
  UNIQUE KEY uk_meeting_sync_outbox_scope (enterprise_id, id),
  UNIQUE KEY uk_meeting_sync_outbox_0 (enterprise_id, binding_id, business_key),
  KEY idx_meeting_sync_outbox_0 (status, next_attempt_at, id),
  CONSTRAINT fk_meeting_sync_outbox_enterprise FOREIGN KEY (enterprise_id) REFERENCES enterprise(id),
  CONSTRAINT fk_meeting_sync_outbox_binding FOREIGN KEY (enterprise_id, binding_id) REFERENCES meeting_binding(enterprise_id, id),
  CONSTRAINT fk_meeting_sync_outbox_run FOREIGN KEY (enterprise_id, run_id) REFERENCES agent_run(enterprise_id, id),
  CONSTRAINT ck_meeting_sync_outbox_revision CHECK (revision > 0),
  CONSTRAINT ck_meeting_sync_outbox_status CHECK (status IN ('pending','delivered','failed','blocked')),
  CONSTRAINT ck_meeting_sync_outbox_version CHECK (delivered_version <= desired_version),
  CONSTRAINT ck_meeting_sync_outbox_attempt CHECK (attempt_count >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='系统到飞书的版本化投递箱，栅栏领取、幂等创建、字段级补写';
